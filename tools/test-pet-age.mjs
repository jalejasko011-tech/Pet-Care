import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const context={window:{},document:{documentElement:{lang:'sr'}},Date,Intl};vm.createContext(context);
vm.runInContext(readFileSync('www/record-safety.js','utf8'),context);
vm.runInContext(readFileSync('www/pet-age.js','utf8'),context);
const a=context.window.petCareAge,d=s=>new Date(s+'T12:00:00');
assert.equal(a.total({birth:'2024-01-31'},d('2024-02-28')),0);
assert.equal(a.total({birth:'2024-01-31'},d('2024-02-29')),1);
assert.equal(a.total({birth:'2024-02-29'},d('2025-02-28')),12);
assert.equal(a.total({birth:'2030-01-01'},d('2026-10-26')),null);
assert.equal(a.total({},d('2026-10-26')),null);
assert.equal(a.total({birth:'2026-10-26'},new Date(2026,9,26,1)),0);
assert.equal(a.total({ageTotalMonths:1,ageAsOf:'2026-09-26'},new Date(2026,9,26,1)),2);
assert.equal(a.total({ageTotalMonths:27,ageAsOf:'2026-10-26'},d('2026-11-25')),27);
assert.equal(a.total({ageTotalMonths:27,ageAsOf:'2026-10-26'},d('2026-11-26')),28);
assert.equal(a.total({ageTotalMonths:0,ageAsOf:'2026-10-26'},d('2026-10-26')),0);
const records=context.window.petCareRecords;
assert.throws(()=>records.validate({pets:[{id:'p',name:'Luna',ageTotalMonths:-1}]}));
assert.throws(()=>records.validate({pets:[{id:'p',name:'Luna',ageTotalMonths:1.5}]}));
assert.throws(()=>records.validate({pets:[{id:'p',name:'Luna',ageAsOf:'2026-02-30'}]}));
records.validate({pets:[{id:'p',name:'Luna',birth:'',ageTotalMonths:27,ageAsOf:'2026-10-26'}]});
assert.equal(a.birthValue('29','2','2024','2026-10-26'),'2024-02-29');
assert.equal(a.birthValue('29','2','2023','2026-10-26'),null);
assert.equal(a.birthValue('31','4','2020','2026-10-26'),null);
assert.equal(a.birthValue('27','10','2026','2026-10-26'),null);
assert.equal(a.birthValue('','','','2026-10-26'),'');
assert.equal(a.birthValue('1','','2020','2026-10-26'),null);
console.log('PASS direct birth dates and pet age: calendar anniversaries, leap years, unknown/newborn age, advancing estimates and backup validation.');
