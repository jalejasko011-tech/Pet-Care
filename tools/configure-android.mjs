import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
const vars='android/variables.gradle';
let text=readFileSync(vars,'utf8');
for(const key of ['compileSdkVersion','targetSdkVersion']) {
 if(!new RegExp(key+'\\s*=\\s*\\d+').test(text))throw Error('Missing Android SDK setting: '+key);
 text=text.replace(new RegExp(key+'\\s*=\\s*\\d+'),key+' = 36');
}
writeFileSync(vars,text);
const build='android/build.gradle';
text=readFileSync(build,'utf8').replace(/com\.android\.tools\.build:gradle:[\d.]+/,'com.android.tools.build:gradle:8.9.1');
writeFileSync(build,text);
console.log('Android compile/target API 36 configured with AGP 8.9.1 for Google Play.');

// Native launcher resources are regenerated by Capacitor; apply the supplied brand every build.
const { spawnSync } = await import('node:child_process');
const icons = spawnSync('java', ['-Djava.awt.headless=true', 'tools/GenerateLauncherIcons.java'], {stdio:'inherit'});
if (icons.status !== 0) throw Error('Android launcher artwork generation failed');
const appGradle='android/app/build.gradle';
const app=readFileSync(appGradle,'utf8').replace(/versionCode\s+\d+/, 'versionCode 7').replace(/versionName\s+"[^"]+"/, 'versionName "1.6"');
writeFileSync(appGradle,app);

mkdirSync('android/app/src/main/res/raw',{recursive:true});
copyFileSync('www/petcare_chime.wav','android/app/src/main/res/raw/petcare_chime.wav');
